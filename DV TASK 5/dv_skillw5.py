import pandas as pd
import numpy as np

from google.colab import drive
drive.mount('/content/drive')

df= pd.read_csv('/content/drive/MyDrive/DV/healthcare_dataset.csv')

print(df.head())

print(df.info())

print(df.isnull().sum())

df["Date of Admission"] = pd.to_datetime(
    df["Date of Admission"], errors="coerce")

df["Discharge Date"] = pd.to_datetime(
    df["Discharge Date"], errors="coerce"
)

df["Hospital Stay"] = (
    df["Discharge Date"] -
    df["Date of Admission"]
).dt.days

df["Admission Type"] = (
    df["Admission Type"]
    .str.strip()
    .str.title()
)

valid_types = ["Emergency", "Elective", "Urgent"]

df = df[df["Admission Type"].isin(valid_types)]

print("\nDemographics by Medical Condition:")
print(pd.crosstab(
    df["Medical Condition"],
    df["Gender"]
))

print("\nAge Statistics:")
print(
    df.groupby("Medical Condition")["Age"]
    .agg(["count", "mean", "min", "max"])
)

print("\nBilling Statistics:")
print(df["Billing Amount"].describe())

print("\nHospital Stay Statistics:")
print(df["Hospital Stay"].describe())

print("\nCondition-wise Summary:")
print(
    df.groupby("Medical Condition").agg({
        "Billing Amount": ["mean", "median"],
        "Hospital Stay": ["mean", "median"]
    })
)