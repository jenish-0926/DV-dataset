import pandas as pd
df = pd.read_csv('/content/drive/MyDrive/DV/StudentsPerformance.csv')

df.head()

df.isnull().sum()

"""**1. STANDARDIZE / CLEAN CATEGORICAL FEATURES**"""

cat={
    'gender',
    'race/ethnicity',
    'parental level of education',
    'lunch',
    'test preparation course'
}
for i in cat:
  df[i]=df[i].str.strip().str.lower()

df.head()

"""**2. STATISTICAL MEASURES FOR SUBJECT SCORES**"""

subjects = ['math score', 'reading score', 'writing score']
print("Mean")
print(df[subjects].mean())
print("Median")
print(df[subjects].median())
print("Standard deviation")
print(df[subjects].std())
print("quantile")
print(df[subjects].quantile([0.25, 0.50, 0.75]))

"""**3. CREATE TOTAL MARKS AND PERCENTAGE**"""

df['total_mark']=df['math score']+df['reading score']+df['writing score']
df['percentage'] = (df['total_mark'] / 300) * 100

print("\nCalculated Features:")
df.head()

"""** 4. DETECT EXTREME PERFORMANCE OUTLIERS
 Using IQR method**


> Add blockquote


"""

subject_columns = [
    "math score",
    "reading score",
    "writing score"
]

for col in subject_columns:

    Q1 = df[col].quantile(0.25)
    Q3 = df[col].quantile(0.75)

    IQR = Q3 - Q1

    lower_limit = Q1 - 1.5 * IQR
    upper_limit = Q3 + 1.5 * IQR

    outliers = df[
        (df[col] < lower_limit) |
        (df[col] > upper_limit)
    ]

    print("\n----------------------------")
    print("Subject:", col)
    print("Q1:", Q1)
    print("Median:", df[col].median())
    print("Q3:", Q3)
    print("IQR:", IQR)
    print("Lower Limit:", lower_limit)
    print("Upper Limit:", upper_limit)
    print("Number of Outliers:", len(outliers))

    if len(outliers) > 0:
        print("Outlier Scores:")
        print(outliers[col].values)